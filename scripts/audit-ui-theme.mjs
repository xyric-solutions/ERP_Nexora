import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const lists = await Promise.all(
    entries.map((e) => (e.isDirectory() ? walk(resolve(dir, e.name)) : [resolve(dir, e.name)])),
  );
  return lists.flat();
}
const sources = (await walk(resolve(root, "app"))).filter((p) => /\.(?:tsx?|css)$/.test(p)).sort();
const fixedPalette =
  /(?<![\w-])(?:text|bg|border(?:-[trblxy])?|ring(?:-offset)?|outline|divide|fill|stroke|from|via|to|shadow|decoration|placeholder|accent|caret)-(?:black|white|(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)-\d{2,3})(?![\w-])/;
const literalColor = /(?:#[0-9a-f]{3,8}\b|\b(?:rgba?|hsla?|oklch|oklab)\(\s*[-\d.])/i;
const namedColor =
  /(?:^|[;{\s])(?:color|background(?:-color)?|border(?:-color)?)\s*:\s*(?:white|black|red|blue|green)\b/i;
const fonts = [],
  colors = [],
  views = [];
for (const file of sources) {
  const name = relative(root, file).replaceAll("\\", "/"),
    raw = await readFile(file, "utf8");
  const text = raw.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "));
  const isView = /^app\/features\/[^/]+\/views\/.*\.tsx$/.test(name);
  if (isView) views.push(name);
  // Central definitions and the deliberately monochrome print stylesheet are
  // authorities, not per-screen escapes from them.
  const paletteAuthority = name === "app/shared/styles/theme-colors.css" || name === "app/shared/styles/print.css";
  for (const [index, line] of text.split(/\r?\n/).entries()) {
    const family = line.match(/(?:font-family\s*:|fontFamily\s*:\s*)([^;}\n]+)/i),
      utility = line.match(/font-\[([^\]]+)\]/);
    if (
      (family &&
        !/var\(--(?:nx-font|font-)/.test(family[1]) &&
        !/^\s*["']?(?:inherit|unset)["']?\s*$/.test(family[1])) ||
      (utility && !utility[1].includes("var(--nx-font-")) ||
      (name !== "app/layout.tsx" && line.includes('from "next/font/'))
    ) {
      fonts.push({ file: name, line: index + 1, sample: line.trim() });
    }
    if (!paletteAuthority && (fixedPalette.test(line) || literalColor.test(line) || namedColor.test(line)))
      colors.push({ file: name, line: index + 1, sample: line.trim() });
  }
}
const countFiles = (items) => new Set(items.map((i) => i.file)).size;
const fontViews = views.filter((v) => fonts.some((f) => f.file === v)),
  colorViews = views.filter((v) => colors.some((f) => f.file === v));
const percentage = (n) => ((100 * n) / views.length).toFixed(2) + "%";
const rows = (items) =>
  items
    .map(
      (i) =>
        `| [${i.file}:${i.line}](../../${i.file}#L${i.line}) | ${i.sample.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll("|", "\\|").replaceAll("`", "&#96;").slice(0, 230)} |`,
    )
    .join("\n");
const report = `# ERP global typography and theme source audit

Generated by \`node scripts/audit-ui-theme.mjs --write\`.

This is a static source audit. The percentage denominator is **${views.length} feature view TSX files**, not the 802 menu routes. Several routes share renderers and shared components; these figures must not be presented as a measured percentage of rendered screens. Inherited component styles, hidden dialogs, chart artwork and all runtime states need browser verification when touched. Source matches are review candidates rather than proof of a visible defect.

| Direct exceptions in feature view files | Files | Share |
| --- | ---: | ---: |
| Font families outside central tokens | ${fontViews.length}/${views.length} | ${percentage(fontViews.length)} |
| Colours outside central semantic tokens | ${colorViews.length}/${views.length} | ${percentage(colorViews.length)} |

Across all ${sources.length} application TS/TSX/CSS files: ${countFiles(fonts)} files contain candidate font overrides and ${countFiles(colors)} files contain candidate colour overrides (${colors.length} matching lines). Shared-source findings below can affect more routes than the view-only percentage.

The root layout loads Source Sans 3 and Geist Mono for the whole application. Typography tokens and the legacy serif/display aliases resolve centrally; deliberate code/identifier monospace uses the global mono token. Global theme colours are defined in app/shared/styles/theme-colors.css and mapped to Tailwind in app/globals.css. Root theme switching applies app-wide, but fixed palette utilities do not follow future semantic colour changes. Print CSS is intentionally excluded from colour exceptions because it uses a monochrome output palette.

## Font candidates

${fonts.length ? "| Source | Declaration |\n| --- | --- |\n" + rows(fonts) : "None found."}

## Colour candidates

${colors.length ? "| Source | Declaration |\n| --- | --- |\n" + rows(colors) : "None found."}

## Audit scope

Scans literal colour syntax, named CSS colours and fixed Tailwind palette utilities; checks font-family declarations, arbitrary font utilities and additional Next font imports. It does not interpret the full CSS cascade, computed expressions, external libraries or image pixels. Keep legitimate branding, charts, print and icon exceptions explicit. Resolve screen exceptions while implementing that screen, and verify light/dark states and responsive widths before marking it complete.
`;
const destination = resolve(root, "docs/architecture/global-theme-audit.md");
if (process.argv.includes("--write")) await writeFile(destination, report);
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== report)
    throw Error("Theme audit is stale. Run node scripts/audit-ui-theme.mjs --write and review the findings.");
}
console.log(
  JSON.stringify({
    scope: "feature view TSX files; direct source declarations only",
    views: views.length,
    fontExceptions: fontViews.length,
    fontPercentage: percentage(fontViews.length),
    colorExceptions: colorViews.length,
    colorPercentage: percentage(colorViews.length),
    applicationSourceFiles: sources.length,
    allSourceColorFiles: countFiles(colors),
    allSourceColorLines: colors.length,
  }),
);
